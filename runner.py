import csv
import io
import json
import mimetypes
import os
import secrets
import subprocess
import threading
import time
import urllib.request
import uuid
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, HTTPServer
from urllib.parse import parse_qs, urlparse

PORT = 8000
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
STATIC_DIR = os.path.join(BASE_DIR, "static")
DATA_DIR = os.path.join(BASE_DIR, "data")
SCREENSHOT_DIR = os.path.join(STATIC_DIR, "screenshots")
INDEX_FILE = os.path.join(DATA_DIR, "scans.json")

# Ensure all essential directories and files exist safely
os.makedirs(STATIC_DIR, exist_ok=True)
os.makedirs(DATA_DIR, exist_ok=True)
os.makedirs(SCREENSHOT_DIR, exist_ok=True)

if not os.path.exists(INDEX_FILE):
    with open(INDEX_FILE, "w", encoding="utf-8") as f:
        json.dump({}, f)

TASKS = {}

def load_scans():
    if not os.path.exists(INDEX_FILE):
        return {}
    try:
        with open(INDEX_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}

def save_scans(data):
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(INDEX_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)

def capture_screenshot(url, output_path):
    """Takes a headless screenshot using Google Chrome installed on macOS."""
    chrome_paths = [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium"
    ]
    binary = next((p for p in chrome_paths if os.path.exists(p)), None)
    if not binary:
        return False

    try:
        subprocess.run([
            binary,
            "--headless",
            "--disable-gpu",
            "--hide-scrollbars",
            f"--screenshot={output_path}",
            "--window-size=1280,720",
            url
        ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=8)
        return os.path.exists(output_path)
    except Exception:
        return False

def run_recon_task(domain, task_id):
    try:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        rand_key = secrets.token_hex(4)
        scan_folder_name = f"{domain}_{timestamp}_{rand_key}"
        scan_dir = os.path.join(DATA_DIR, scan_folder_name)
        os.makedirs(scan_dir, exist_ok=True)

        TASKS[task_id]['progress'] = 10
        TASKS[task_id]['message'] = 'Harvesting subdomains across registries...'

        script_path = os.path.join(BASE_DIR, "recon.sh")
        proc = subprocess.Popen(
            ["/bin/bash", script_path, domain, scan_dir],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            cwd=BASE_DIR
        )

        count_file = os.path.join(scan_dir, "count.txt")
        
        # Real-time monitoring loop
        while proc.poll() is None:
            time.sleep(1)
            # Check if count.txt has been generated by recon.sh
            if os.path.exists(count_file):
                try:
                    with open(count_file, "r") as cf:
                        total_found = cf.read().strip()
                        if total_found:
                            TASKS[task_id]['progress'] = 55
                            TASKS[task_id]['message'] = f'Discovered {total_found} subdomains! Probing HTTP response codes...'
                except Exception:
                    pass
            else:
                if TASKS[task_id]['progress'] < 45:
                    TASKS[task_id]['progress'] += 5

        if proc.returncode != 0:
            TASKS[task_id]['status'] = 'failed'
            TASKS[task_id]['message'] = 'Enumeration script failed.'
            return

        json_file = os.path.join(scan_dir, f"recon_dash_{domain}.json")
        if not os.path.exists(json_file):
            TASKS[task_id]['status'] = 'failed'
            TASKS[task_id]['message'] = f'Results file not found in {scan_folder_name}'
            return

        with open(json_file, "r", encoding="utf-8") as f:
            scan_payload = json.load(f)

        live_hosts = scan_payload.get("live_hosts", [])
        ok_hosts = [h for h in live_hosts if h.get("is_200")]
        total_ok = len(ok_hosts)

        TASKS[task_id]['progress'] = 75
        TASKS[task_id]['message'] = f'Probed live hosts. Capturing snapshots for {total_ok} active HTTP 200 services...'

        # Cap screenshots to 30 to prevent UI lag on huge targets
        screenshot_targets = ok_hosts[:30]
        for idx, host_obj in enumerate(screenshot_targets):
            host = host_obj["host"]
            TASKS[task_id]['progress'] = 75 + int((idx / max(1, len(screenshot_targets))) * 23)
            TASKS[task_id]['message'] = f'Capturing snapshot [{idx + 1}/{len(screenshot_targets)}]: {host}'

            shot_name = f"{scan_folder_name}_{host.replace('.', '_')}.png"
            shot_file = os.path.join(SCREENSHOT_DIR, shot_name)

            if not os.path.exists(shot_file):
                capture_screenshot(f"https://{host}", shot_file)

            if os.path.exists(shot_file):
                host_obj["screenshot"] = f"/screenshots/{shot_name}"

        # Register scan metadata
        scan_id = scan_folder_name
        scan_record = {
            "id": scan_id,
            "folder": scan_folder_name,
            "domain": domain,
            "started_at": datetime.now(timezone.utc).isoformat(),
            "status": "completed",
            "subdomains": scan_payload.get("subdomains", []),
            "live_hosts": live_hosts
        }

        with open(os.path.join(scan_dir, "scan_result.json"), "w", encoding="utf-8") as f:
            json.dump(scan_record, f, indent=2)

        scans = load_scans()
        scans[scan_id] = scan_record
        save_scans(scans)

        TASKS[task_id]['progress'] = 100
        TASKS[task_id]['status'] = 'completed'
        TASKS[task_id]['message'] = f'Scan complete! {len(scan_payload.get("subdomains", []))} subdomains cataloged.'
        TASKS[task_id]['scan_id'] = scan_id
        TASKS[task_id]['subdomains_count'] = len(scan_payload.get("subdomains", []))
        TASKS[task_id]['live_count'] = total_ok

    except Exception as e:
        TASKS[task_id]['status'] = 'failed'
        TASKS[task_id]['message'] = str(e)
class ReconHandler(BaseHTTPRequestHandler):
    def _set_cors(self):
        self.send_header('Access-Control-Allow-Origin', '*')
        self.send_header('Access-Control-Allow-Methods', 'GET, POST, OPTIONS')
        self.send_header('Access-Control-Allow-Headers', 'Content-Type, Authorization')

    def do_OPTIONS(self):
        self.send_response(204)
        self._set_cors()
        self.end_headers()

    def do_GET(self):
        parsed = urlparse(self.path)
        path = parsed.path
        query = parse_qs(parsed.query)

        # 1. Async task progress polling
        if path == '/api/task-status':
            tid = query.get('id', [''])[0]
            if tid in TASKS:
                return self._send_json(200, TASKS[tid])
            return self._send_json(404, {'detail': 'Task not found'})

        # 2. List scans
        if path == '/api/scans':
            domain = query.get('domain', [''])[0].strip().lower()
            scans = load_scans()
            results = [{
                'id': sid,
                'domain': s.get('domain'),
                'started_at': s.get('started_at'),
                'status': s.get('status', 'completed'),
                'count': len(s.get('subdomains', []))
            } for sid, s in scans.items() if not domain or s.get('domain', '').lower() == domain]
            results.sort(key=lambda x: x['started_at'], reverse=True)
            return self._send_json(200, results)

        # 3. Retrieve specific scan
        if path.startswith('/api/scans/') and not any(path.endswith(x) for x in ['/export', '/report', '/diff']):
            sid = path.split('/')[3]
            scans = load_scans()
            if sid in scans:
                return self._send_json(200, scans[sid])
            return self._send_json(404, {'detail': 'Scan not found'})

        # 4. Export JSON / CSV
        if path.startswith('/api/scans/') and path.endswith('/export'):
            parts = path.split('/')
            scan_id = parts[3]
            fmt = query.get('format', ['json'])[0]
            scans = load_scans()
            if scan_id not in scans:
                return self._send_json(404, {'detail': 'Scan not found'})
            scan = scans[scan_id]
            if fmt == 'csv':
                out = io.StringIO()
                writer = csv.writer(out)
                writer.writerow(['name', 'status_code', 'is_200'])
                live_map = {x['host']: x.get('status_code', '') for x in scan.get('live_hosts', [])}
                for s in scan.get('subdomains', []):
                    code = live_map.get(s['name'], '')
                    writer.writerow([s['name'], code, code == 200])
                return self._send_raw(200, 'text/csv', out.getvalue().encode('utf-8'))
            return self._send_json(200, scan)

        # 5. Markdown report
        if path.startswith('/api/scans/') and path.endswith('/report'):
            scan_id = path.split('/')[3]
            scans = load_scans()
            if scan_id not in scans:
                return self._send_json(404, {'detail': 'Scan not found'})
            scan = scans[scan_id]
            ok_count = sum(1 for h in scan.get('live_hosts', []) if h.get('status_code') == 200 or h.get('is_200'))
            report = (
                f"# Reconnaissance Report: {scan['domain']}\n\n"
                f"- **Scan ID**: `{scan_id}`\n"
                f"- **Folder**: `{scan.get('folder', scan_id)}`\n"
                f"- **Date**: {scan['started_at']}\n"
                f"- **Total Discovered**: {len(scan['subdomains'])}\n"
                f"- **Active (HTTP 200 OK)**: {ok_count}\n"
                f"- **Total Responding**: {len(scan.get('live_hosts', []))}\n"
            )
            return self._send_raw(200, 'text/markdown', report.encode('utf-8'))

        # 6. Diff comparison
        if path.startswith('/api/scans/') and path.endswith('/diff'):
            sid = path.split('/')[3]
            comp_id = query.get('compare_to', [''])[0]
            scans = load_scans()
            if sid not in scans or comp_id not in scans:
                return self._send_json(404, {'detail': 'Scan not found'})
            newer = {s['name'] for s in scans[sid].get('subdomains', [])}
            older = {s['name'] for s in scans[comp_id].get('subdomains', [])}
            return self._send_json(200, {
                'new': sorted(list(newer - older)),
                'removed': sorted(list(older - newer)),
                'unchanged': sorted(list(newer & older))
            })

        # 7. Static file & screenshot delivery
        clean_path = path.lstrip('/')
        if clean_path in ('', 'index.html'):
            target_file = os.path.join(STATIC_DIR, 'index.html')
        elif clean_path in ('history', 'history.html'):
            target_file = os.path.join(STATIC_DIR, 'history.html')
        else:
            target_file = os.path.join(STATIC_DIR, clean_path)

        if os.path.isfile(target_file):
            content_type, _ = mimetypes.guess_type(target_file)
            content_type = content_type or 'application/octet-stream'
            with open(target_file, 'rb') as f:
                return self._send_raw(200, f'{content_type}', f.read())

        self._send_json(404, {'detail': 'File not found'})

    def do_POST(self):
        parsed = urlparse(self.path)

        # Trigger async recon task
        if parsed.path == '/api/run-recon-async':
            length = int(self.headers.get('Content-Length', 0))
            try:
                body = json.loads(self.rfile.read(length).decode('utf-8'))
                domain = body.get('domain', '').strip().lower()
            except Exception:
                domain = ''

            if not domain:
                return self._send_json(400, {'detail': 'Domain is required'})

            task_id = str(uuid.uuid4())
            TASKS[task_id] = {
                'status': 'running',
                'progress': 0,
                'message': 'Starting enumeration task...',
                'domain': domain
            }

            thread = threading.Thread(target=run_recon_task, args=(domain, task_id), daemon=True)
            thread.start()

            return self._send_json(200, {'task_id': task_id})

        # Manual import handler
        if parsed.path == '/api/import':
            content_type = self.headers.get('Content-Type', '')
            if 'multipart/form-data' not in content_type:
                return self._send_json(400, {'detail': 'Expected multipart/form-data'})

            length = int(self.headers.get('Content-Length', 0))
            raw_body = self.rfile.read(length)

            boundary = content_type.split('boundary=')[-1].encode()
            parts = raw_body.split(b'--' + boundary)

            domain = ''
            file_bytes = b''
            filename = ''

            for part in parts:
                if b'name="domain"' in part:
                    domain = part.split(b'\r\n\r\n')[1].split(b'\r\n')[0].decode('utf-8').strip()
                elif b'name="file"' in part:
                    header, body = part.split(b'\r\n\r\n', 1)
                    file_bytes = body.rsplit(b'\r\n', 1)[0]
                    if b'filename="' in header:
                        filename = header.split(b'filename="')[1].split(b'"')[0].decode('utf-8')

            if not domain or not file_bytes:
                return self._send_json(400, {'detail': 'Domain and file are required'})

            subdomains = []
            live_hosts = []

            if filename.endswith('.csv') or file_bytes.startswith(b'name'):
                reader = csv.DictReader(io.StringIO(file_bytes.decode('utf-8', errors='ignore')))
                for row in reader:
                    name = row.get('name', '').strip()
                    if name:
                        subdomains.append({'name': name, 'sources': ['manual-import']})
            else:
                try:
                    parsed_json = json.loads(file_bytes.decode('utf-8'))
                    if isinstance(parsed_json, dict):
                        raw_subs = parsed_json.get('subdomains', [])
                        for item in raw_subs:
                            if isinstance(item, str):
                                subdomains.append({'name': item, 'sources': ['manual-import']})
                            elif isinstance(item, dict) and 'name' in item:
                                subdomains.append(item)
                        live_hosts = parsed_json.get('live_hosts', [])
                    elif isinstance(parsed_json, list):
                        for item in parsed_json:
                            subdomains.append({'name': item if isinstance(item, str) else item.get('name', ''), 'sources': ['manual-import']})
                except Exception as e:
                    return self._send_json(400, {'detail': f'Failed to parse file: {str(e)}'})

            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            rand_key = secrets.token_hex(4)
            scan_folder_name = f"{domain}_{timestamp}_{rand_key}"
            scan_dir = os.path.join(DATA_DIR, scan_folder_name)
            os.makedirs(scan_dir, exist_ok=True)

            scan_record = {
                'id': scan_folder_name,
                'folder': scan_folder_name,
                'domain': domain,
                'started_at': datetime.now(timezone.utc).isoformat(),
                'status': 'completed',
                'subdomains': subdomains,
                'live_hosts': live_hosts
            }

            with open(os.path.join(scan_dir, "scan_result.json"), "w", encoding="utf-8") as f:
                json.dump(scan_record, f, indent=2)

            scans = load_scans()
            scans[scan_folder_name] = scan_record
            save_scans(scans)

            return self._send_json(200, {
                'id': scan_folder_name,
                'subdomains': len(subdomains),
                'live_hosts': len(live_hosts)
            })

        self._send_json(404, {'detail': 'Route not found'})

    def _send_json(self, status, payload):
        self._send_raw(status, 'application/json', json.dumps(payload).encode('utf-8'))

    def _send_raw(self, status, content_type, body_bytes):
        self.send_response(status)
        self._set_cors()
        self.send_header('Content-Type', content_type)
        self.send_header('Content-Length', str(len(body_bytes)))
        self.end_headers()
        self.wfile.write(body_bytes)

if __name__ == '__main__':
    server = HTTPServer(('127.0.0.1', PORT), ReconHandler)
    print(f'[*] Recon Dashboard & Runner listening on: http://127.0.0.1:{PORT}')
    print(f'[*] Storing scans in: {DATA_DIR}')
    server.serve_forever()